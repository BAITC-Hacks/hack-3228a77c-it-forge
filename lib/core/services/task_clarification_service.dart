/// Local, topic-based fallback until a model-backed API is configured.
List<Map<String, dynamic>> questionsForTask(String task) {
  final text = task.toLowerCase();
  bool has(List<String> words) => words.any(text.contains);
  if (has(['гүл', 'цвет', 'flower', 'букет'])) return flowerQuestions;

  Map<String, dynamic> question(
    String context,
    String prompt,
    List<String> choices,
  ) => {
    'context': context,
    'question': prompt,
    'options': [
      for (var i = 0; i < choices.length; i++)
        AiQuestionOption(id: i, label: choices[i], badge: 'Нұсқа ${i + 1}'),
      const AiQuestionOption(
        id: 3,
        label: 'Өз нұсқамды жазу...',
        badge: 'Өз жауабым',
        isCustom: true,
      ),
    ],
  };

  if (has(['логист', 'жеткіз', 'курьер', 'достав', 'көлік', 'маршрут'])) {
    return [
      question(
        'Жеткізу үдерісі',
        'Жеткізу тапсырмасында алдымен нені жақсарту керек?',
        [
          'Курьерлердің бағыттарын оңтайландыру',
          'Тапсырыстың күйін картадан бақылау',
          'Қойма мен жеткізу есебін біріктіру',
        ],
      ),
      question(
        'Бастапқы деректер',
        'Жоспарлау үшін қандай деректер қолжетімді?',
        [
          'Тапсырыс мекенжайлары мен уақыт аралықтары',
          'Көлік GPS деректері және өткен сапарлар',
          'Деректерді жаңадан жинау керек',
        ],
      ),
      question(
        'Нәтижені бағалау',
        'Жеткізу шешімінің нәтижесін қалай бағалайсыз?',
        [
          'Жеткізу уақытының қысқаруы',
          'Жанармай мен тасымал шығынының азаюы',
          'Уақтылы жеткізілген тапсырыстар үлесі',
        ],
      ),
    ];
  }
  if (has(['дүкен', 'сататын', 'сауда', 'магазин', 'сату', 'shop', 'тауар'])) {
    return [
      question(
        'Каталог және тапсырыс',
        'Сату қосымшасында клиент не істей алуы керек?',
        [
          'Тауарды іздеу, сүзу және себетке қосу',
          'Тапсырыс беріп, онлайн төлеу',
          'Сатушымен кеңесіп, тапсырыс беру',
        ],
      ),
      question('Сатушы кабинеті', 'Сатушыға қандай басқару құралдары қажет?', [
        'Тауарлар мен қалдықтарды басқару',
        'Тапсырыстар мен жеткізуді басқару',
        'Сатылымдар мен клиенттерді талдау',
      ]),
      question(
        'Алғашқы нұсқа',
        'Сату сервисінің алғашқы нұсқасы қайда жұмыс істесін?',
        [
          'Телефонға бейімделген веб-сайт',
          'Android және iOS қосымшасы',
          'Веб-сайт пен мобильді қосымша',
        ],
      ),
    ];
  }
  if (has(['оқу', 'білім', 'сабақ', 'курс', 'мектеп', 'обуч', 'school'])) {
    return [
      question('Оқу форматы', 'Білім беру шешімінде сабақтар қалай өтеді?', [
        'Бейнесабақтар мен материалдарды өздігінен оқу',
        'Мұғаліммен онлайн сабақ',
        'Тапсырмалар мен тест арқылы жаттығу',
      ]),
      question('Қатысушылар', 'Қандай пайдаланушы кабинеттері қажет?', [
        'Оқушы және мұғалім',
        'Оқушы, мұғалім және ата-ана',
        'Курс авторы және әкімші',
      ]),
      question('Оқу нәтижесі', 'Оқу жетістігін қалай бақылау керек?', [
        'Тест нәтижелері мен прогресс',
        'Мұғалімнің тапсырманы бағалауы',
        'Курс соңындағы қорытынды жоба',
      ]),
    ];
  }
  final context = task.length > 180 ? '${task.substring(0, 180)}…' : task;
  return [
    question('Мақсат және аудитория', '«$context» — шешімді кім қолданады?', [
      'Клиенттер немесе сатып алушылар',
      'Компания қызметкерлері',
      'Компаниялар мен серіктестер',
    ]),
    question(
      'Негізгі нәтиже',
      'Осы тапсырманың алғашқы нұсқасында қандай нәтиже қажет?',
      [
        'Идеяны тексеретін интерактивті прототип',
        'Негізгі үдерісті орындайтын жұмыс істейтін қосымша',
        'Қолданыстағы жүйені жақсарту немесе автоматтандыру',
      ],
    ),
    question(
      'Қабылдау критерийлері',
      'Тапсырманың сәтті орындалғанын қалай тексереміз?',
      [
        'Негізгі әрекеттерді пайдаланушылармен сынау',
        'Уақыт пен шығынның өзгерісін өлшеу',
        'Алдын ала келісілген талаптар бойынша тексеру',
      ],
    ),
  ];
}
